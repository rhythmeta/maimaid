package org.rhythmeta.maimaid.core.data

import android.content.Context
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import org.rhythmeta.maimaid.BuildConfig

/**
 * Deployment values for the international-server (SDGA) import.
 *
 * Supplied at build time through the single `MAIMAID_SDGA` environment variable (a JSON
 * object) or the gitignored `local-secrets/sdga.json`, exactly like [SgwcmaidConfig].
 * `build.gradle.kts` turns either input into the `sdga_config.json` asset, so editing the
 * local file invalidates the Gradle task instead of leaving a stale value in the
 * configuration cache. An unset variable yields an empty config and the feature reports
 * `sdga_not_configured`.
 *
 * [keychip], [placeId] and [regionId] are only a last-resort cabinet: the build-time places
 * catalog normally supplies a real arcade, and the cabinet identity has to match the place
 * that is written into the login request.
 */
@Serializable
data class SdgaConfig(
    val titleServerUrl: String = "",
    val aesKey: String = "",
    val aesIv: String = "",
    val obfuscateParam: String = "",
    val commonKey: String = "",
    val aimeHost: String = "",
    val aimePort: Int = 22345,
    val gameVersion: String = "1.65",
    val gameId: String = "SDGA",
    val keychip: String = "",
    val placeId: Int = 0,
    val regionId: Int = 0,
) {
    /**
     * The title server only needs the transport secrets; the cabinet values come from the
     * catalog. The AES key is 32 characters (AES-256) and the AiMeDB key is exactly 16
     * bytes (AES-128), matching the two independent ciphers of this deployment.
     */
    val isComplete: Boolean
        get() = titleServerUrl.isNotBlank() && aesKey.length == 32 && aesIv.length == 16 &&
            obfuscateParam.isNotBlank() && commonKey.length == 16 && aimeHost.isNotBlank()

    /** The servlet base always ends with `/`; every API appends only its own hash. */
    val servletBase: String
        get() = if (titleServerUrl.endsWith('/')) titleServerUrl else "$titleServerUrl/"
}

internal object SdgaBuildConfig {
    private val json = Json { ignoreUnknownKeys = true }

    /** Generated by the `prepareSdgaAssets` task; `{}` when the build has no secrets. */
    internal const val CONFIG_ASSET = "sdga_config.json"

    fun load(context: Context): SdgaConfig = try {
        val text = context.assets.open(CONFIG_ASSET).bufferedReader().use { it.readText() }
        parse(text)
    } catch (error: Exception) {
        if (BuildConfig.DEBUG) {
            android.util.Log.w("SdgaConfig", "failed to load $CONFIG_ASSET", error)
        }
        SdgaConfig()
    }

    internal fun parse(text: String): SdgaConfig =
        runCatching { json.decodeFromString<SdgaConfig>(text) }
            .onFailure { error ->
                if (BuildConfig.DEBUG) {
                    android.util.Log.w("SdgaConfig", "invalid SDGA config JSON", error)
                }
            }
            .getOrDefault(SdgaConfig())
}
